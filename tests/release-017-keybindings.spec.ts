import {test,expect} from '@playwright/test';
test('v0.1.7 keybinding editor saves and restores shortcuts without breaking lobby, chat or combat',async({page,baseURL})=>{
 test.setTimeout(180000);
 const errors:string[]=[];page.on('pageerror',err=>errors.push(err.message));
 const moves:{x:number;z:number}[]=[];
 page.on('websocket',socket=>socket.on('framesent',frame=>{
  try{const message=JSON.parse(String(frame.payload));if(message.type==='input')moves.push(message.move);}catch{}
 }));
 await page.goto(baseURL+'/?room=keys017'+crypto.randomUUID().replaceAll('-').slice(0,16));
 await expect(page.locator('#room-panel')).toContainText('Connected',{timeout:30000});
 const openOptions=async()=>{await page.locator('#options-button').click();await expect(page.locator('#keybindings')).toBeVisible()};
 await openOptions();
 await expect(page.locator('.keybinding-row')).toHaveCount(12);
 const movement=page.getByRole('button',{name:'Rebind Move forward'});
 const ability1=page.getByRole('button',{name:'Rebind Ability 1'});
 const chat=page.getByRole('button',{name:'Rebind Open room chat'});
 await expect(movement).toHaveText('W');
 await movement.click();await page.keyboard.press('s');
 await expect(page.locator('#keybinding-feedback')).toContainText('already used for Move backward');
 await expect(movement).toHaveText('Press any key…');
 await page.keyboard.press('ArrowUp');
 await expect(movement).toHaveText('↑');
 await expect(page.locator('#instructions')).toContainText('↑/');
 await ability1.click();await page.keyboard.press('5');
 await expect(ability1).toHaveText('5');
 await expect(page.locator('.ability-slot[data-slot="1"] kbd')).toHaveText('5');
 await chat.click();await page.keyboard.press('t');
 await expect(chat).toHaveText('T');
 await expect(page.locator('#room-chat small')).toContainText('T to chat');
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('jacworks-keybindings-v1')??'null'));
 expect(saved).toMatchObject({forward:'arrowup',ability1:'5',chat:'t'});
 // Opening chat is never allowed while the Options dialog has keyboard focus.
 await page.keyboard.press('t');await expect(page.locator('#chat-input')).toBeHidden();
 await page.getByRole('button',{name:'Close',exact:true}).last().click();
 await page.keyboard.press('t');await expect(page.locator('#chat-input')).toBeVisible();
 await page.keyboard.press('Escape');await expect(page.locator('#chat-input')).toBeHidden();
 await page.locator('#game').click({position:{x:15,y:15}});
 await page.keyboard.down('ArrowUp');
 await expect.poll(()=>moves.some(move=>move.z===1),{timeout:5000}).toBeTruthy();
 await page.keyboard.up('ArrowUp');
 await page.keyboard.press('5');
 await expect(page.locator('.ability-slot[data-slot="1"] .cooldown-text')).toContainText(/[0-9]/,{timeout:5000});
 await page.reload();
 await expect(page.locator('#room-panel')).toContainText('Connected',{timeout:30000});
 await openOptions();
 await expect(page.getByRole('button',{name:'Rebind Ability 1'})).toHaveText('5');
 await expect(page.locator('.ability-slot[data-slot="1"] kbd')).toHaveText('5');
 await page.getByRole('button',{name:'Rebind Ability 1'}).click();
 await page.keyboard.press('Escape');
 await expect(page.getByRole('button',{name:'Rebind Ability 1'})).toHaveText('5');
 await expect(page.locator('#keybindings')).toBeVisible();
 await page.getByRole('button',{name:'Restore default keybindings'}).click();
 await expect(page.getByRole('button',{name:'Rebind Move forward'})).toHaveText('W');
 await expect(page.getByRole('button',{name:'Rebind Ability 1'})).toHaveText('1');
 await expect(page.locator('.ability-slot[data-slot="1"] kbd')).toHaveText('1');
 await expect(page.locator('#room-chat small')).toContainText('Enter to chat');
 await expect(page.evaluate(()=>JSON.parse(localStorage.getItem('jacworks-keybindings-v1')??'null').chat)).resolves.toBe('enter');
 expect(errors).toEqual([]);
});
