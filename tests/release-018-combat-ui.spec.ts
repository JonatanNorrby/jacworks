import {test,expect} from '@playwright/test';
import {emptyInventory,type Inventory} from '../shared/inventory';

test('0.1.8 Wardrobe filters by slot, persists selected tab when equipping, and opens from hub',async({page,baseURL})=>{
 test.setTimeout(120000);
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 const inv:Inventory=emptyInventory();
 inv.rewards={'hat-cone-a':'conicalTaper','hat-cone-b':'conicalTaper','hat-cone-c':'conicalTaper','boot-large':'largeSphere','boot-ball':'sphericalBall'};
 inv.hats=1;inv.fleetfootPairs=1;
 await page.addInitScript(raw=>localStorage.setItem('jacworks-inventory-v1',raw),JSON.stringify(inv));
 await page.goto(baseURL+'/?room=wardrobe018'+crypto.randomUUID().replaceAll('-').slice(0,16));
 await expect(page.locator('#room-panel')).toContainText('Connected',{timeout:30000});
 await page.getByRole('button',{name:'Wardrobe',exact:true}).click();
 const panel=page.locator('#inventory-panel');
 await expect(panel).toBeVisible();await expect(panel).toContainText('Owned equipment');
 const tabs=panel.getByRole('navigation',{name:'Wardrobe equipment slots'});
 await expect(tabs.getByRole('button')).toHaveCount(6);
 await expect(panel.locator('.gear-card')).toHaveCount(2);
 await tabs.getByRole('button',{name:'Head (1)'}).click();
 await expect(tabs.getByRole('button',{name:'Head (1)'})).toHaveAttribute('aria-pressed','true');
 await expect(panel.locator('.gear-card')).toHaveCount(1);
 await expect(panel.locator('.gear-card')).toContainText('Pointy Hat');
 await panel.locator('.gear-card').getByRole('button',{name:'Equip'}).click();
 await expect(tabs.getByRole('button',{name:'Head (1)'})).toHaveAttribute('aria-pressed','true');
 await expect(panel.locator('.gear-card')).toContainText('Equipped');
 await tabs.getByRole('button',{name:'Boots (1)'}).click();
 await expect(panel.locator('.gear-card')).toHaveCount(1);
 await expect(panel.locator('.gear-card')).toContainText('Fleetfoot Boots');
 await panel.locator('.gear-card').getByRole('button',{name:'Equip'}).click();
 await expect(tabs.getByRole('button',{name:'Boots (1)'})).toHaveAttribute('aria-pressed','true');
 await tabs.getByRole('button',{name:'Offhand (0)'}).click();
 await expect(panel.locator('.wardrobe-empty')).toContainText('No offhand equipment owned');
 await tabs.getByRole('button',{name:'All (2)'}).click();
 await expect(panel.locator('.gear-card')).toHaveCount(2);
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('jacworks-inventory-v1')??'{}'));
 expect(saved).toMatchObject({head:'pointyHat',boots:'fleetfootBoots'});
 await panel.getByRole('button',{name:'Close'}).click();
 await page.getByRole('button',{name:'Propose boss'}).click();
 await page.getByRole('combobox',{name:'Boss encounter'}).selectOption('warden');
 await page.getByRole('button',{name:'Propose encounter'}).click();
 await page.getByRole('button',{name:'Accept'}).click();
 await expect(page.locator('#boss-label')).toContainText('WARDEN',{timeout:15000});
 expect(errors).toEqual([]);
});
